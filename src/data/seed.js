export const seedAudit = (customers) => {
  const entries = [];
  const push = (c, action, by, at, detail = '') =>
    entries.push({ id: uid('aud'), customerId: c.id, customerCode: c.code || '(draft)', businessName: c.businessName, action, by, at, detail });
  customers.forEach((c) => {
    push(c, 'Created', c.createdBy, c.createdAt, 'Application created');
    if (c.status !== STATUS.DRAFT) push(c, 'Submitted', c.createdBy, c.createdAt, 'Submitted for verification');
    // Activation is stamped with activatedAt when the seed provides one, otherwise a day before the last update.
    const activatedAt = c.activatedAt || new Date(new Date(c.updatedAt).getTime() - 86400000).toISOString();
    if ([STATUS.APPROVAL, STATUS.ACTIVE, STATUS.SUSPENDED].includes(c.status)) push(c, 'Verified', 'Mahbub Hasan', activatedAt, 'Documents and outlet verified');
    if ([STATUS.ACTIVE, STATUS.SUSPENDED].includes(c.status)) push(c, 'Approved', 'Nasrin Sultana', activatedAt, 'Customer activated');
    if (c.status === STATUS.RETURNED) push(c, 'Returned for Correction', 'Mahbub Hasan', c.updatedAt, c.statusReason);
    if (c.status === STATUS.REJECTED) push(c, 'Rejected', 'Mahbub Hasan', c.updatedAt, c.statusReason);
    if (c.status === STATUS.SUSPENDED) push(c, 'Suspended', 'Nasrin Sultana', c.updatedAt, c.statusReason);
    if (c.credit.status === CREDIT_STATUS.APPROVED) push(c, 'Credit Approved', c.credit.decisionBy, c.credit.decisionAt, `Limit ${c.credit.approvedLimit}, ${c.credit.paymentTerms} (${c.credit.approvedCreditDays} credit days)`);
  });
  return entries.sort((a, b) => new Date(b.at) - new Date(a.at));
};
